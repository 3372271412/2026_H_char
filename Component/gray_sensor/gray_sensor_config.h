#ifndef GRAY_SENSOR_CONFIG_H
#define GRAY_SENSOR_CONFIG_H

/*
 * ──────────────────────────────────────────────────────────────────────────
 *  灰度传感器固定配置
 * ──────────────────────────────────────────────────────────────────────────
 *  传感器型号：无 MCU 基础款，黑线白底。
 *  硬件结构：板载 74HC4051 八选一模拟多路复用器，
 *            PB0/PB1/PB10 输出 3 位地址选择 CH1~CH8，
 *            PB25 (ADC0_CH4) 采集选中通道的模拟输出。
 *  采集流程：逐路切换地址 → 等待稳定 → ADC 采样 → 多次平均。
 *  本文件参数描述传感器硬件特性和标定状态，安装高度或光照变化后
 *  需要重新标定 WHITE/BLACK 数组。
 */

/* ── 通道数与 ADC 量程 ─────────────────────────────────────────────────── */

/* 物理通道数：8 路灰度传感器，对应板载 74HC4051 的 8 个输入。 */
#define GRAY_SENSOR_CHANNEL_COUNT             8U

/* ADC 满量程：12 位 ADC，最大值 4095。
 * 归一化后 normalized 的范围就是 0~4095：
 *   normalized = 0    → 纯黑（raw ≤ black 标定值）
 *   normalized = 4095 → 纯白（raw ≥ white 标定值）
 * 循迹算法中 black_strength = 4095 - normalized，黑色越深数值越大。 */
#define GRAY_SENSOR_ADC_FULL_SCALE            4095U

/* ── 采样参数 ─────────────────────────────────────────────────────────── */

/* 每通道 ADC 采样次数，取平均抑制噪声。8 次 → 每路耗时约 0.8ms，
 * 8 路共约 6.4ms，在 10ms 控制周期内可完成。 */
#define GRAY_SENSOR_ADC_SAMPLES_PER_CHANNEL   8U

/* 切换 74HC4051 地址后等待模拟输出稳定的时间（微秒）。
 * 太短会采到切换瞬间的毛刺；太大则 8 路总采样时间超出 10ms 周期。 */
#define GRAY_SENSOR_ADDRESS_SETTLE_US         10U

/* 单次 ADC 转换超时时间（微秒）。超时说明 ADC 硬件异常，
 * scan_raw 返回 false，service 层据此报 ADC 故障停车。 */
#define GRAY_SENSOR_ADC_TIMEOUT_US            100U

/* ── 标定有效性 ────────────────────────────────────────────────────────── */

/* 标定跨度最小值：white - black 的最小允许差值。
 * 跨度 < 此值 → 该通道标定无效（传感器坏线/安装太高/光照不足），
 * valid_mask 对应位不置 1，service 层检查 valid_mask != 0xFF 时报 CAL 故障。
 * 当前值 100 约为满量程 4095 的 2.4%，低于此说明该路几乎无法区分黑白。 */
#define GRAY_SENSOR_MIN_CALIBRATION_SPAN       100U

/* ── 判线阈值（无滞回，供循迹算法使用）─────────────────────────────────── */

/* 强黑判定阈值：归一化后的黑色强度 ≥ 此值才算"明确黑线通道"。
 * black_strength = 4095 - normalized，所以 normalized ≤ 3095 时
 * black_strength ≥ 1000 → 判为强黑。
 * 当前值 1000 约为满量程 24%，低于此说明该路确实压在黑线上。 */
#define GRAY_SENSOR_LINE_STRONG_MIN           1000U

/* “最多几路强黑仍算普通线”和“几路强黑算检查点”属于任务策略，
 * 已分别放入 g_task2/4/5/6_params.line，避免调一个任务影响其他任务。 */

/* ── 物理安装方向 ────────────────────────────────────────────────────────── */

/* 传感器倒装时设为 1，使数组下标仍保持"左到右"物理顺序。
 * 正常安装（芯片朝下、线序从左到右对应 CH1~CH8）= 0。
 * 倒装时 ADC 扫描顺序与物理左右相反，设为 1 后 scan_raw 自动反转下标。 */
#define GRAY_SENSOR_REVERSE_ORDER              0

/* ── 标定就绪标志 ────────────────────────────────────────────────────────── */

/* 完成实车白/黑各 200 帧标定并替换下方数组后，必须手动改为 1。
 * 为 0 时 service 层拒绝启动循迹，报 CALIBRATION 故障，
 * 防止用临时/默认值直接驱动实车。 */
#define GRAY_SENSOR_CALIBRATION_READY          1

/* ── 逐路标定值（核心数据）─────────────────────────────────────────────────
 *
 * 这两个数组是灰度循迹的基础——每路传感器在白底和黑线上的 ADC 原始值。
 * 它们的用途：
 *   1. 归一化：把各路不同的 ADC 动态范围统一映射到 0~4095，消除硬件差异
 *      normalized = (raw - black) × 4095 / (white - black)
 *   2. 滞回二值化：生成 digital_mask（1=白/0=黑），带滞回防抖
 *
 * 逐路标定的必要性（以当前标定值为例）：
 *   CH4 的 span = 1865 - 88 = 1777（最宽）
 *   CH5 的 span = 991 - 89 = 902（最窄，仅为 CH4 的 51%）
 *   不逐路标定的话，统一阈值在某些通道会误判。
 *
 * 何时需要重新标定：
 *   - 传感器安装高度变化
 *   - 更换赛道材质/颜色
 *   - 环境光照大幅变化
 *   - 更换传感器模块或 LED 老化
 * 标定流程：白底采 200 帧取平均 → 替换 WHITE_VALUES；
 *          黑线采 200 帧取平均 → 替换 BLACK_VALUES；
 *          确认每路 span ≥ 100，然后设 CALIBRATION_READY = 1。
 */

#define GRAY_SENSOR_WHITE_VALUES \
    {3231U,3034U,3152U,3113U,3183U,3024U,2709U,2768U}
#define GRAY_SENSOR_BLACK_VALUES \
    {377U,81U,116U,167U,162U,117U,87U,83U}

#endif /* GRAY_SENSOR_CONFIG_H */